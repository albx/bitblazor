namespace BitBlazor.Components;

/// <summary>
/// Represents the position of the dropdown menu relative to its toggle button.
/// </summary>
public enum DropdownPosition
{
    /// <summary>
    /// The dropdown menu is positioned below the toggle button. Default value.
    /// </summary>
    Down,

    /// <summary>
    /// The dropdown menu is positioned above the toggle button.
    /// </summary>
    Up,

    /// <summary>
    /// The dropdown menu is positioned to the right of the toggle button.
    /// </summary>
    End,

    /// <summary>
    /// The dropdown menu is positioned to the left of the toggle button.
    /// </summary>
    Start
}
