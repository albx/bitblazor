namespace BitBlazor.Components;

/// <summary>
/// Represents the width options for a dropdown menu in a dropdown component.
/// </summary>
public enum DropdownMenuWidth
{
    /// <summary>
    /// Default width, which is determined by the content of the dropdown menu.
    /// </summary>
    Default,

    /// <summary>
    /// Full width, which makes the dropdown menu expand to the full width of its parent container.
    /// </summary>
    Full
}
